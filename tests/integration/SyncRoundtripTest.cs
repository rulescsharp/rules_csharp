using System;
using System.Diagnostics;
using System.IO;
using RulesCsharp.Tests;

var sync = Runfiles.Find("//csharp:sync", key => key.EndsWith("csharp/sync" + (OperatingSystem.IsWindows() ? ".exe" : ""), StringComparison.Ordinal));
Console.WriteLine($"Using sync tool: {sync}");

var workspace = Path.Combine(Environment.GetEnvironmentVariable("TEST_TMPDIR") ?? Path.GetTempPath(), "sync_ws");
var lib = Path.Combine(workspace, "src", "SampleLib");
Directory.CreateDirectory(lib);
File.WriteAllText(Path.Combine(lib, "Greeter.cs"), """
    namespace SampleLib;
    public class Greeter
    {
        public static string Greet() => "Hello, World!";
    }
    """);
File.WriteAllText(Path.Combine(lib, "BUILD.bazel"), """
    load("@rules_csharp//csharp:defs.bzl", "csharp_library")

    csharp_library(
        name = "sample_lib",
        srcs = ["Greeter.cs"],
    )
    """);

int Sync(params string[] args)
{
    var psi = new ProcessStartInfo(sync) { UseShellExecute = false };
    psi.ArgumentList.Add("--workspace=" + workspace);
    foreach (var arg in args)
    {
        psi.ArgumentList.Add(arg);
    }
    using var process = Process.Start(psi)!;
    process.WaitForExit();
    return process.ExitCode;
}

void Expect(bool condition, string failure)
{
    if (!condition)
    {
        throw new Exception("FAILED: " + failure);
    }
}

bool FileHas(string path, string text) => File.ReadAllText(path).Contains(text, StringComparison.Ordinal);

// 1. Generate the csproj
Expect(Sync() == 0, "sync exited nonzero.");
var csproj = Path.Combine(lib, "sample_lib.bazel.csproj");
Expect(File.Exists(csproj), $"Expected {csproj} to be generated by CsprojSync.");
Console.WriteLine("Generated csproj content:");
Console.WriteLine(File.ReadAllText(csproj));

// 2. The generated csproj lists sources explicitly
Expect(FileHas(csproj, "<EnableDefaultItems>false</EnableDefaultItems>"), "<EnableDefaultItems>false</EnableDefaultItems> missing from generated csproj.");
Expect(FileHas(csproj, "<Compile Include=\"Greeter.cs\" />"), "<Compile Include=\"Greeter.cs\" /> missing from generated csproj.");
Expect(FileHas(csproj, "<Reference Include=\"sample_lib\">"), "Reference to target missing from generated csproj.");
Expect(FileHas(csproj, ".ref.dll</HintPath>"), "Reference HintPath does not point to .ref.dll.");

// 3. Round trip is idempotent
Expect(Sync("--check") == 0, "--check failed right after sync.");
Console.WriteLine("Idempotency check passed.");

// 4. A new source file without a sync makes --check fail
File.WriteAllText(Path.Combine(lib, "Helper.cs"), "namespace SampleLib;\npublic class Helper { public static int MagicNumber => 42; }\n");
Expect(Sync("--check") != 0, "--check should have failed when new .cs file was added without syncing.");
Console.WriteLine("--check correctly detected out-of-sync workspace.");
Expect(Sync() == 0, "sync exited nonzero.");
Expect(FileHas(csproj, "<Compile Include=\"Helper.cs\" />"), "Helper.cs not included in updated csproj.");
Expect(Sync("--check") == 0, "--check failed after resync.");

// 5. --bootstrap-lock writes Directory.Packages.props and packages.lock.json
File.WriteAllText(Path.Combine(lib, "SampleWithPkgs.csproj"), """
    <Project Sdk="Microsoft.NET.Sdk">
      <PropertyGroup>
        <TargetFramework>net8.0</TargetFramework>
      </PropertyGroup>
      <ItemGroup>
        <PackageReference Include="Newtonsoft.Json" Version="13.0.3" />
        <PackageReference Include="Serilog" Version="3.1.1" />
      </ItemGroup>
    </Project>
    """);
Expect(Sync("--bootstrap-lock") == 0, "sync --bootstrap-lock exited nonzero.");
var props = Path.Combine(workspace, "Directory.Packages.props");
var lockFile = Path.Combine(workspace, "packages.lock.json");
Expect(File.Exists(props), "Directory.Packages.props was not created by --bootstrap-lock.");
Expect(File.Exists(lockFile), "packages.lock.json was not created by --bootstrap-lock.");
Expect(FileHas(props, "<PackageVersion Include=\"Newtonsoft.Json\" Version=\"13.0.3\""), "Newtonsoft.Json not found in bootstrapped Directory.Packages.props.");
Expect(FileHas(lockFile, "\"Newtonsoft.Json\""), "Newtonsoft.Json not found in bootstrapped packages.lock.json.");
Console.WriteLine("--bootstrap-lock verified successfully.");

Console.WriteLine("Round-trip synchronization verified successfully.");
return 0;
